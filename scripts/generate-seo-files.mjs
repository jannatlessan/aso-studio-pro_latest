// Generates public/sitemap.xml, public/robots.txt, public/llms.txt and public/llms-full.txt from
// src/data/tools.json, src/data/games.json and src/data/toolDocs.json.
// Run locally with `npm run gen:seo` and commit the output: <lastmod> comes from the git history
// of each page's source file (Vercel's shallow clone cannot give reliable dates, so this is NOT
// part of the Vercel build).
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { dirname, join, relative } from 'node:path';

const BASE = 'https://shaaddev.studio';
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => readFileSync(join(root, p), 'utf8');
const tools = JSON.parse(read('src/data/tools.json'));
const games = JSON.parse(read('src/data/games.json'));
const docs = JSON.parse(read('src/data/toolDocs.json'));

const gitDate = (...files) => {
  let best = '';
  for (const f of files) {
    try {
      const d = execFileSync('git', ['log', '-1', '--format=%cs', '--', f], { cwd: root, encoding: 'utf8' }).trim();
      if (d > best) best = d;
    } catch { /* ignore */ }
  }
  return best || new Date().toISOString().slice(0, 10);
};

// url path -> source file, found from each page's canonical SEO url.
const pageFile = {};
const walk = (dir) => {
  for (const n of readdirSync(dir)) {
    const p = join(dir, n);
    if (statSync(p).isDirectory()) walk(p);
    else if (n.endsWith('.tsx')) {
      for (const m of readFileSync(p, 'utf8').matchAll(/url="https:\/\/shaaddev\.studio(\/[^"]*)?"/g)) {
        pageFile[m[1] || '/'] ??= relative(root, p);
      }
    }
  }
};
walk(join(root, 'src/pages'));

const staticPages = [
  ['/', 1.0, 'weekly'], ['/tools', 0.9, 'weekly'], ['/games', 0.7, 'weekly'], ['/microsaas', 0.6, 'monthly'],
  ['/apps/stamppedia', 0.6, 'monthly'], ['/apps/stamppedia/privacy', 0.3, 'yearly'], ['/apps/stamppedia/terms', 0.3, 'yearly'],
  ['/about', 0.5, 'yearly'], ['/contact', 0.5, 'yearly'], ['/privacy', 0.3, 'yearly'], ['/terms', 0.3, 'yearly']
];
const urls = [];
for (const [p, pr, cf] of staticPages) urls.push({ p, pr, cf, d: gitDate(pageFile[p] || 'src/App.tsx', ...(p === '/tools' ? ['src/data/tools.json'] : [])) });
for (const t of tools) urls.push({ p: t.path, pr: 0.8, cf: 'monthly', d: gitDate(pageFile[t.path] || 'src/App.tsx', 'src/data/toolDocs.json') });
for (const g of games) urls.push({ p: g.path, pr: 0.5, cf: 'monthly', d: gitDate(pageFile[g.path] || 'src/App.tsx') });

writeFileSync(join(root, 'public/sitemap.xml'),
  `<?xml version="1.0" encoding="UTF-8"?>\n<!-- Generated by scripts/generate-seo-files.mjs (npm run gen:seo). Do not edit by hand. -->\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n` +
  urls.map((u) => `  <url><loc>${BASE}${u.p === '/' ? '/' : u.p}</loc><lastmod>${u.d}</lastmod><changefreq>${u.cf}</changefreq><priority>${u.pr.toFixed(1)}</priority></url>`).join('\n') +
  `\n</urlset>\n`);

const aiBots = ['GPTBot', 'OAI-SearchBot', 'ChatGPT-User', 'ClaudeBot', 'Claude-User', 'Claude-SearchBot', 'PerplexityBot', 'Perplexity-User', 'Google-Extended', 'Applebot-Extended'];
writeFileSync(join(root, 'public/robots.txt'),
  `# shaaddev.studio - all crawlers welcome, including AI search and assistant crawlers.\n` +
  `# Generated by scripts/generate-seo-files.mjs.\n\nUser-agent: *\nAllow: /\n\n` +
  aiBots.map((b) => `User-agent: ${b}\nAllow: /\n`).join('\n') +
  `\nSitemap: ${BASE}/sitemap.xml\n`);

const cats = [...new Set(tools.map((t) => t.category))];
const llms = `# ${docs.site.name}

> ${docs.site.summary}

Every tool is free and runs in a modern web browser; no sign-in is needed. Each tool page has a "Quick facts" section (input, output, limits, privacy) and an FAQ. Full details for every tool: ${BASE}/llms-full.txt

${cats.map((c) => `## ${c}\n\n` + tools.filter((t) => t.category === c).map((t) => `- [${t.name}](${BASE}${t.path}): ${t.description}`).join('\n')).join('\n\n')}

## Games

- [Browser games](${BASE}/games): ${games.length} free casual games (puzzle, word, arcade) that run in the browser.

## Optional

- [About](${BASE}/about)
- [Contact](${BASE}/contact)
- [Privacy policy](${BASE}/privacy)
- [Tool feed (JSON)](${BASE}/tools.json): machine-readable list of all tools and games.
`;
writeFileSync(join(root, 'public/llms.txt'), llms);

const full = `# ${docs.site.name}: full tool reference

> ${docs.site.summary}

${docs.site.analytics}

` + tools.map((t) => {
  const d = docs.tools[t.path];
  return `## ${t.name}

URL: ${BASE}${t.path}
Category: ${t.category}
${t.description}

- Who it is for: ${d.who}
- Input: ${d.input}
- Output: ${d.output}
- Limits: ${d.limits}
- Privacy: ${d.privacy}

How to use:
${d.steps.map((s, i) => `${i + 1}. ${s}`).join('\n')}

FAQ:
${d.faq.map((f) => `- Q: ${f.q}\n  A: ${f.a}`).join('\n')}
`;
}).join('\n');
writeFileSync(join(root, 'public/llms-full.txt'), full);
console.log(`gen:seo: sitemap ${urls.length} urls, robots.txt, llms.txt, llms-full.txt`);
